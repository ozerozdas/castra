-- Public profile mirror of the Better Auth `user` table, kept in sync by @castra-kit/auth (ADR 0023).
-- App tables reference it with foreign keys. It has no policy in castra.config.ts, so it is not exposed.
CREATE TABLE users (
  id TEXT PRIMARY KEY NOT NULL,
  email TEXT NOT NULL UNIQUE,
  name TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- The example table. Primary keys are TEXT uuids generated by the API (same type as user ids).
CREATE TABLE notes (
  id TEXT PRIMARY KEY NOT NULL,
  owner_id TEXT NOT NULL REFERENCES users (id),
  title TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  is_public INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE INDEX idx_notes_owner_id ON notes (owner_id);
CREATE INDEX idx_notes_is_public_created_at ON notes (is_public, created_at);
