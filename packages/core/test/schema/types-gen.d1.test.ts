import { beforeAll, describe, expect, it } from "vitest";
import { generateKyselyTypes, introspect } from "../../src/schema/index.js";
import { applyFixture, d1Query } from "./fixture.js";

const EXPECTED = `// Generated by \`castra generate\`. Do not edit; re-run the command after changing the schema.
import type { Generated } from "kysely";

export interface CastraAuditTable {
  id: string;
  action: string;
}

export interface PostTagsTable {
  post_id: number;
  tag: string;
  weight: number | null;
}

export interface PostsTable {
  id: Generated<number>;
  author_id: string;
  parent_id: number | null;
  title: string;
  score: Generated<number | null>;
  views: Generated<number>;
  price: number | null;
  cover: ArrayBuffer | null;
  payload: ArrayBuffer | null;
  status: Generated<string>;
}

export interface UsersTable {
  id: string;
  email: string;
  name: string | null;
  created_at: Generated<string>;
}

export interface WeirdNameTable {
  "odd col": string | null;
}

export interface DB {
  _castra_audit: CastraAuditTable;
  post_tags: PostTagsTable;
  posts: PostsTable;
  users: UsersTable;
  "weird \\"name\\"": WeirdNameTable;
}
`;

describe("generateKyselyTypes", () => {
  let types: string;
  beforeAll(async () => {
    await applyFixture();
    types = generateKyselyTypes(await introspect(d1Query, { generatedAt: "x" }));
  });

  it("matches the expected output for the fixture schema", () => {
    expect(types).toBe(EXPECTED);
  });

  it("does not depend on generatedAt", async () => {
    const other = generateKyselyTypes(await introspect(d1Query, { generatedAt: "y" }));
    expect(other).toBe(types);
  });

  it("disambiguates colliding interface names", () => {
    const empty = { columns: [], primaryKey: [], foreignKeys: [], indexes: [] };
    const out = generateKyselyTypes({
      version: 1,
      generatedAt: "x",
      tables: { a_b: { name: "a_b", ...empty }, aB: { name: "aB", ...empty }, "1st": { name: "1st", ...empty } },
    });
    expect(out).toContain("export interface ABTable {");
    expect(out).toContain("export interface ABTable2 {");
    expect(out).toContain("export interface T1stTable {");
    expect(out).toContain('  "1st": T1stTable;');
  });
});
