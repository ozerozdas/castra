import type { ColumnSnapshot, SchemaSnapshot, SqliteAffinity, TableSnapshot } from "../types.js";

const TS_TYPES: Record<SqliteAffinity, string> = {
  INTEGER: "number",
  REAL: "number",
  NUMERIC: "number",
  TEXT: "string",
  BLOB: "ArrayBuffer",
};

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Property key: bare when it is a valid identifier, otherwise a JSON-quoted string. */
function propertyKey(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

function pascalCase(name: string): string {
  const words = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const joined = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");
  return /^[0-9]/.test(joined) ? `T${joined}` : joined || "Table";
}

/** True when SQLite fills the column in on insert: it has a default, or it is a rowid alias. */
function isGenerated(table: TableSnapshot, column: ColumnSnapshot): boolean {
  if (column.defaultValue !== null) return true;
  return table.primaryKey.length === 1 && column.primaryKeyPosition === 1 && column.type === "INTEGER";
}

function columnType(table: TableSnapshot, column: ColumnSnapshot): string {
  const base = TS_TYPES[column.affinity];
  const value = column.notNull ? base : `${base} | null`;
  return isGenerated(table, column) ? `Generated<${value}>` : value;
}

/**
 * Emit a TypeScript declaration file for Kysely: one interface per table plus `export interface DB`.
 *
 * Mapping: INTEGER/REAL/NUMERIC -> `number`, TEXT -> `string`, BLOB -> `ArrayBuffer`; columns that are
 * not `NOT NULL` get `| null`; columns with a default value or an `INTEGER PRIMARY KEY` are wrapped in
 * Kysely's `Generated<T>`. Output is a pure function of the snapshot (no timestamps) and ends with a
 * newline, so it can be committed and compared byte for byte.
 */
export function generateKyselyTypes(snapshot: SchemaSnapshot): string {
  const tables = Object.values(snapshot.tables).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

  const used = new Set<string>(["DB"]);
  const interfaceNames = new Map<string, string>();
  for (const table of tables) {
    const base = `${pascalCase(table.name)}Table`;
    let candidate = base;
    for (let i = 2; used.has(candidate); i++) candidate = `${base}${i}`;
    used.add(candidate);
    interfaceNames.set(table.name, candidate);
  }

  const out: string[] = [
    "// Generated by `castra generate`. Do not edit; re-run the command after changing the schema.",
    'import type { Generated } from "kysely";',
    "",
  ];

  for (const table of tables) {
    out.push(`export interface ${interfaceNames.get(table.name)} {`);
    for (const column of table.columns) {
      out.push(`  ${propertyKey(column.name)}: ${columnType(table, column)};`);
    }
    out.push("}", "");
  }

  out.push("export interface DB {");
  for (const table of tables) {
    out.push(`  ${propertyKey(table.name)}: ${interfaceNames.get(table.name)};`);
  }
  out.push("}", "");

  return out.join("\n");
}
