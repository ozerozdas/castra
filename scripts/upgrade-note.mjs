#!/usr/bin/env node
/* global console, process, URL */
/**
 * Generates the "Template changes" section of docs/upgrading/<version>.md from the template diff between the release
 * the note starts from (`<!-- upgrade-from: vX.Y.Z -->` in the note) and v<version> (or the working tree before that
 * tag exists). Issue #19, ADR 0083.
 *
 *   node scripts/upgrade-note.mjs <version> --write   # (re)write the generated section of one note
 *   node scripts/upgrade-note.mjs --check             # CI: every note's section matches the template diff
 *
 * package.json is not diffed: dependency changes become `pnpm add` / `pnpm remove` commands and script changes a JSON
 * block, so the note applies to a project whatever its package.json looks like.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO = fileURLToPath(new URL("..", import.meta.url));
const TEMPLATE = "packages/create-castra/template";
const NOTES = join(REPO, "docs/upgrading");
// Same as RENAMES in packages/create-castra/src/scaffold.ts.
const RENAMES = { _gitignore: ".gitignore", "_dev.vars.example": ".dev.vars.example" };
export const START = "<!-- template-diff:start (generated by scripts/upgrade-note.mjs; do not edit by hand) -->";
export const END = "<!-- template-diff:end -->";

const git = (...args) => execFileSync("git", args, { cwd: REPO, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

function tagExists(tag) {
  try {
    git("rev-parse", "--verify", "--quiet", `refs/tags/${tag}`);
    return true;
  } catch {
    return false;
  }
}

/** Project path of a template path (`_gitignore` → `.gitignore`). */
const projectPath = (rel) => RENAMES[rel] ?? rel;

/** File at `ref` (or the working tree when `ref` is undefined). */
const show = (ref, rel) => (ref ? git("show", `${ref}:${TEMPLATE}/${rel}`) : readFileSync(join(REPO, TEMPLATE, rel), "utf8"));

function packageChanges(from, to, version) {
  const before = JSON.parse(show(from, "package.json"));
  const after = JSON.parse(show(to, "package.json"));
  const commands = [];
  for (const [section, flag] of [["dependencies", ""], ["devDependencies", " -D"]]) {
    const a = before[section] ?? {};
    const b = after[section] ?? {};
    const add = Object.keys(b)
      .filter((d) => d.startsWith("@castra-kit/") || a[d] !== b[d])
      .sort()
      .map((d) => `${d}@${d.startsWith("@castra-kit/") ? version : b[d]}`);
    const remove = Object.keys(a).filter((d) => !(d in b)).sort();
    if (add.length) commands.push(`pnpm add${flag} ${add.join(" ")}`);
    if (remove.length) commands.push(`pnpm remove ${remove.join(" ")}`);
  }
  const sa = before.scripts ?? {};
  const sb = after.scripts ?? {};
  const scripts = Object.fromEntries(Object.keys(sb).filter((k) => sa[k] !== sb[k]).map((k) => [k, sb[k]]));
  const removedScripts = Object.keys(sa).filter((k) => !(k in sb));
  return { commands, scripts, removedScripts };
}

/** The generated section for a note upgrading `from` → `version`. */
export function section(from, version) {
  const to = tagExists(`v${version}`) ? `v${version}` : undefined;
  const range = to ? [from, to] : [from];
  const files = git("diff", "--name-only", ...range, "--", TEMPLATE)
    .split("\n")
    .filter(Boolean)
    .map((p) => p.slice(TEMPLATE.length + 1))
    .filter((p) => p !== "package.json")
    .sort();
  const out = [START, "", `## Template changes since ${from}`, ""];
  const pkg = packageChanges(from, to, version);
  out.push("Packages (if a removed one is still imported by your own code, keep it):", "", "```bash", ...pkg.commands, "```", "");
  if (Object.keys(pkg.scripts).length || pkg.removedScripts.length) {
    out.push("`package.json` scripts to add or change:", "", "```json", JSON.stringify(pkg.scripts, null, 2), "```", "");
    if (pkg.removedScripts.length) out.push(`Scripts to remove: ${pkg.removedScripts.map((s) => `\`${s}\``).join(", ")}.`, "");
  }
  if (files.length) {
    out.push(
      "Changes to the files the template created. If you have not edited a file, the diff applies as is",
      "(`git apply` with the blocks saved to a file); otherwise merge it by hand.",
      "",
    );
  }
  for (const rel of files) {
    const dest = projectPath(rel);
    const diff = git("diff", ...range, "--", `${TEMPLATE}/${rel}`)
      .split("\n")
      .filter((l) => !l.startsWith("index "))
      .map((l) => l.replaceAll(`a/${TEMPLATE}/${rel}`, `a/${dest}`).replaceAll(`b/${TEMPLATE}/${rel}`, `b/${dest}`))
      .join("\n")
      .trimEnd();
    // Four backticks: the diffs themselves can contain ``` fences (README).
    out.push(`### \`${dest}\``, "", "````diff", diff, "````", "");
  }
  out.push(END);
  return out.join("\n");
}

/** `from` tag recorded in a note, or undefined. */
export function noteFrom(text) {
  return /<!-- upgrade-from: (v\d+\.\d+\.\d+) -->/.exec(text)?.[1];
}

/** The note with its generated section replaced (or appended). */
export function withSection(text, generated) {
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s >= 0 && e > s) return text.slice(0, s) + generated + text.slice(e + END.length);
  return `${text.trimEnd()}\n\n${generated}\n`;
}

function main(argv) {
  if (argv[0] === "--check") {
    let stale = 0;
    for (const file of readdirSync(NOTES).filter((f) => /^\d+\.\d+\.\d+\.md$/.test(f))) {
      const text = readFileSync(join(NOTES, file), "utf8");
      const from = noteFrom(text);
      if (!from) continue;
      if (withSection(text, section(from, file.slice(0, -3))) !== text) {
        console.error(`docs/upgrading/${file} is out of date: run node scripts/upgrade-note.mjs ${file.slice(0, -3)} --write`);
        stale++;
      }
    }
    return stale ? 1 : 0;
  }
  const [version, flag] = argv;
  if (!/^\d+\.\d+\.\d+$/.test(version ?? "") || flag !== "--write") {
    console.error("Usage: node scripts/upgrade-note.mjs <version> --write | --check");
    return 2;
  }
  const path = join(NOTES, `${version}.md`);
  const text = readFileSync(path, "utf8");
  const from = noteFrom(text);
  if (!from) {
    console.error(`${path} has no <!-- upgrade-from: vX.Y.Z --> line.`);
    return 1;
  }
  writeFileSync(path, withSection(text, section(from, version)));
  console.log(`Updated docs/upgrading/${version}.md (${from} -> ${tagExists(`v${version}`) ? `v${version}` : "working tree"}).`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main(process.argv.slice(2));
